import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { overview } from '../src/worker.js';
const db = new DatabaseSync(':memory:');
db.exec(`CREATE TABLE app_records(module TEXT,archived INTEGER); CREATE TABLE social_posts(status TEXT,approved_by TEXT,review_note TEXT DEFAULT '');
INSERT INTO app_records VALUES ('products',0),('products',0),('products',1),('inventory',0);
INSERT INTO social_posts VALUES ('approved',NULL),('approved',''),('approved','   '),('approved','owner@example.com'),('approved','owner@example.com','AI審核：AI_APPROVED；'),('pending_review',NULL),('published','owner@example.com'),('archived','owner@example.com');`);
let reads=0;
const result=await overview({DB:{prepare(sql){reads++;const statement=db.prepare(sql);return {all:async()=>({results:statement.all()})};}}});
assert.equal(result.modules.products,2);
assert.equal(result.modules.inventory,1);
assert.equal(result.modules.orders,0);
assert.equal(result.posts.ai_pending,3);
assert.equal(result.posts.human_approved,1);
assert.equal(result.posts.ai_approved,1,'AI evidence with owner FK must not count as human review');
assert.equal(result.posts.pending_review,1);
assert.equal(result.posts.published,1);
assert.equal(result.posts.archived,undefined);
assert.equal(reads,2,'overview should use two grouped queries rather than sequential module queries');
db.close();
console.log('PASS ERP overview: archived records excluded, AI pre-review separated, empty modules preserved, two grouped reads');
