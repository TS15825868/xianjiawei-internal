import fs from 'node:fs';
const read=p=>fs.readFileSync(new URL(`../${p}`,import.meta.url),'utf8');
const req=(ok,msg)=>{if(!ok)throw new Error(msg)};
const publishing=read('publishing.html');
const erp=read('index.html');
const pkg=read('package.json');
const bridge=read('assets/js/erp-publishing-separation.js');
const app=read('assets/js/publishing-app.js');
req(publishing.includes('貼文審核、排程與正式發布'),'publishing.html 缺少獨立貼文系統主畫面');
req(publishing.includes('/assets/js/publishing-app.js'),'publishing.html 未載入獨立 publishing app');
req(!publishing.includes('庫存中心')&&!publishing.includes('訂單管理')&&!publishing.includes('客戶管理'),'獨立貼文系統混入 ERP 功能');
req(erp.includes('/assets/js/erp-publishing-separation.js'),'ERP 未載入貼文分離守門');
req(erp.includes('href="/publishing.html"'),'ERP 未提供獨立貼文系統入口');
req(bridge.includes("['#posts','#calendar']"),'舊 ERP 貼文／排程網址沒有轉向獨立系統');
req(app.includes("api('/posts')")&&app.includes('/publish-now'),'獨立貼文系統未接正式貼文 API 或立即發布');
req(app.includes('/deliveries'),'獨立貼文系統未接各平台發布結果');
req(pkg.includes('cp publishing.html dist/publishing.html'),'build 沒有部署 publishing.html');
req(pkg.includes('cp assets/js/publishing-app.js dist/assets/js/publishing-app.js'),'build 沒有部署 publishing app');
console.log('PASS：貼文審核／排程／發布已成為獨立前台；ERP 導覽分離，舊 #posts/#calendar 會轉向獨立系統。');
