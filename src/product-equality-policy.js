export function productEqualityErrors(post) {
  const lines = [post?.title, post?.headline, post?.copy, post?.image_alt, post?.sceneBrief]
    .filter(value => typeof value === 'string')
    .flatMap(value => value.normalize('NFKC').split(/[。！？!?；;\n]/u));
  return lines.some(line => PRODUCT_CONTEXT.test(line) && COMPARISON.test(line))
    ? ['產品平等檢查未通過：請客觀描述產品特色、包裝或規格，移除優劣、送禮價值及便利性比較。']
    : [];
}
